"""The works cited in the data, for the generated section of CREDITS.md (ADR 0037)."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator

from .graph import Graph, ore_crosswalk_rows

START = "<!-- works-cited:start (generated by `capabilities credits`; do not edit by hand) -->"
END = "<!-- works-cited:end -->"


@dataclass
class Work:
    citation: str
    link: str | None = None
    statuses: set[str] = field(default_factory=set)
    cited_by: set[str] = field(default_factory=set)


def cited_works(graph: Graph) -> list[Work]:
    """Every distinct citation in the data, with what cites it, alphabetical."""
    works: dict[str, Work] = {}
    for node_id, document in all_documents(graph):
        for reference in references_in(document):
            citation = reference["citation"].strip()
            work = works.setdefault(citation, Work(citation))
            work.link = work.link or link_for(reference)
            work.statuses.add(reference.get("status", "unverified"))
            work.cited_by.add(node_id)
    return sorted(works.values(), key=lambda work: work.citation.casefold())


def works_cited_markdown(works: list[Work]) -> str:
    lines = [f"{len(works)} works are cited in the data. Each line says what cites it and how far the citation has been checked."]
    lines.append("")
    for work in works:
        text = f"[{work.citation}]({work.link})" if work.link else work.citation
        cited_by = ", ".join(f"`{node_id}`" for node_id in sorted(work.cited_by))
        lines.append(f"- {text} *{', '.join(sorted(work.statuses))}*. Cited by {cited_by}.")
    return "\n".join(lines)


def refreshed(text: str, section: str) -> str:
    """The credits text with its generated section replaced."""
    before, start, rest = text.partition(START)
    _, end, after = rest.partition(END)
    if not start or not end:
        raise ValueError("CREDITS.md is missing its works-cited markers")
    return f"{before}{START}\n{section}\n{END}{after}"


def credits_path(root: Path) -> Path:
    return root / "CREDITS.md"


def all_documents(graph: Graph) -> Iterator[tuple[str, dict]]:
    for bucket in (graph.quantities, graph.things, graph.verbs, graph.routes, graph.profiles, graph.jobs, graph.overrides):
        yield from bucket.items()
    yield from ore_crosswalk_references(graph.root)


def ore_crosswalk_references(root: Path) -> Iterator[tuple[str, dict]]:
    """The reference behind each row of the ore crosswalk (ADR 0045), as a document citing it: the mineral's id, or for
    a rejected row, its MRDS name."""
    for row in ore_crosswalk_rows(root):
        reference = {"citation": row["citation"], "supports": row["supports"], "status": row.get("status") or "unverified"}
        if row.get("url"):
            reference["url"] = row["url"]
        yield row["id"] or row["mrds_ore"].lower(), {"references": [reference]}


def references_in(value: object) -> Iterator[dict]:
    """References can sit at any depth (a route's, a quantity value's), so search the whole document."""
    if isinstance(value, dict):
        if isinstance(value.get("citation"), str):
            yield value
        for child in value.values():
            yield from references_in(child)
    elif isinstance(value, list):
        for child in value:
            yield from references_in(child)


def link_for(reference: dict) -> str | None:
    if reference.get("doi"):
        return f"https://doi.org/{reference['doi']}"
    return reference.get("url")
